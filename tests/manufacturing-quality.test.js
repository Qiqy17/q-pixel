"use strict";
const assert=require("node:assert/strict"),quality=require("../web/workspaces/quality-checks.js"),planner=require("../web/make/board-planner.js");
const pattern={width:60,height:40,cells:Array.from({length:40},(_,r)=>Array.from({length:60},(_,c)=>(r===0&&c===59)||(r===39&&c===0)?"H7":(r+c)%7===0?null:"H2"))};
const before=JSON.stringify(pattern),inspection=quality.inspectPattern(pattern,["H2","H7"]);
const boards=planner.splitPattern(pattern,{specId:"standard-29"});
const reconstructed=Array.from({length:pattern.height},()=>Array(pattern.width).fill(null));
for(const board of boards) for(let r=0;r<board.rows;r++) for(let c=0;c<board.columns;c++) reconstructed[board.rowStart+r][board.columnStart+c]=pattern.cells[board.rowStart+r][board.columnStart+c];
assert.deepEqual(reconstructed,pattern.cells,"board coordinates reconstruct original orientation including corner colors");
assert.equal(planner.summarizeBoards(boards).totalCells,inspection.total);
const checks=quality.run({pattern,usage:inspection.usage,validColorCodes:["H2","H7"],exportSettings:{exportMirror:true}});
assert.equal(checks.find(c=>c.id==='pattern-integrity').status,'pass');
assert.match(checks.find(c=>c.id==='output').detail,/镜像/);
assert.match(checks.find(c=>c.id==='output').detail,/不保证 1:1/);
assert.equal(quality.run({pattern,usage:{H2:1}}).find(c=>c.id==='pattern-integrity').status,'error');
assert.equal(quality.run({pattern,usage:inspection.usage,validColorCodes:["H2"]}).find(c=>c.id==='unknown-colors').status,'warning');
assert.equal(quality.inspectPattern({width:2,height:2,cells:[["H2"]]}).valid,false);
const fragments={width:4,height:4,cells:Array.from({length:4},(_,r)=>Array.from({length:4},(_,c)=>(r+c)%2?'H2':'H7'))};
assert.equal(quality.run({pattern:fragments,usage:{H2:8,H7:8}}).find(c=>c.id==='isolated-cells').status,'warning');
assert.equal(JSON.stringify(pattern),before,'quality inspection never recolors or deletes cells');
console.log('manufacturing-quality: counts, unknown colors, fragments, orientation and non-calibrated print notice passed');
