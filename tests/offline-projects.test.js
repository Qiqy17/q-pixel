"use strict";
const assert = require("node:assert/strict");
const api = require("../web/core/offline-projects.js");
const model = require("../web/core/project-model.js");
const local = { id: "a", title: "作品", payload: { pattern: { cells: [["H2"]] } } };
const remote = JSON.parse(JSON.stringify(local));
const hash = (record) => api.fingerprint(record, model.payloadFingerprint);
assert.equal(api.decide(local, null, "", hash), "upload");
assert.equal(api.decide(local, remote, "", hash), "equal");
remote.payload.pattern.cells[0][0] = "H3";
assert.equal(api.decide(local, remote, hash(remote), hash), "upload");
assert.equal(api.decide(local, remote, "", hash), "conflict");
const deleted = { ...local, deleted: true };
assert.notEqual(hash(deleted), hash(local));
assert.notEqual(hash({ ...local, title: "改名" }), hash(local));
assert.notEqual(hash({ ...local, folderId: "f" }), hash(local));
const copy = api.conflictCopy(local, "revision-1");
assert.equal(copy.id, copy.payload.id);
assert.equal(copy.title, copy.payload.title);
assert.equal(copy.conflictOf, local.id);
copy.payload.pattern.cells[0][0] = "E11";
assert.equal(local.payload.pattern.cells[0][0], "H2");
console.log("offline-projects: 共同基线、删除/改名/目录冲突与独立副本通过");
